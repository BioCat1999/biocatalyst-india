#!/usr/bin/env bash
# SETUP-MAC.sh — one-command local setup for the Biocatalyst India web app on macOS.
#
#   1. Double-click the tarball to extract (or: tar -xzf biocatalyst-india-mac.tar.gz)
#   2. In Terminal: cd into the extracted folder
#   3. Run: ./SETUP-MAC.sh
#   4. Open http://localhost:3000 in your browser
#
# Everything runs on YOUR Mac only: Homebrew packages (node, postgresql@16),
# a local Postgres database, and the Next.js app on port 3000. Nothing is
# uploaded anywhere. Keep the Terminal window open while you use the app
# (Ctrl+C stops the server).
#
# Safe to re-run: database role/database creation, migrations and seeding are
# idempotent.
set -euo pipefail

cd "$(dirname "$0")"

echo "==> 1/7 Checking Node.js (needs >= 20)..."
if ! command -v node >/dev/null 2>&1; then
  echo "    node not found — installing via Homebrew (may ask for your password)..."
  brew install node
fi
NODE_MAJOR="$(node -p "process.versions.node.split('.')[0]")"
if [ "$NODE_MAJOR" -lt 20 ]; then
  echo "    node $NODE_MAJOR is too old — installing a newer node via Homebrew..."
  brew install node
fi
echo "    node $(node --version) OK"

echo "==> 2/7 Setting up pnpm..."
corepack enable >/dev/null 2>&1 || true
corepack prepare pnpm@10.34.6 --activate >/dev/null

echo "==> 3/7 Installing PostgreSQL 16 (Homebrew, local only)..."
if ! command -v psql >/dev/null 2>&1; then
  brew install postgresql@16
fi
export PATH="/opt/homebrew/opt/postgresql@16/bin:$PATH"
brew services start postgresql@16 >/dev/null 2>&1 || true
echo "    waiting for Postgres to be ready..."
for _ in $(seq 1 30); do
  if pg_isready >/dev/null 2>&1; then break; fi
  sleep 1
done
pg_isready

echo "==> 4/7 Creating local database role + database (idempotent)..."
psql -d postgres -v ON_ERROR_STOP=1 <<'EOF' >/dev/null
DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'biocatalyst') THEN
    CREATE ROLE biocatalyst LOGIN PASSWORD 'biocatalyst';
  END IF;
END
$$;
EOF
if ! psql -d postgres -tAc "SELECT 1 FROM pg_database WHERE datname='biocatalyst_dev'" | grep -q 1; then
  createdb -O biocatalyst biocatalyst_dev
  echo "    created database biocatalyst_dev"
else
  echo "    database biocatalyst_dev already exists"
fi

echo "==> 5/7 Writing local-only app config (apps/web/.env)..."
ADMIN_TOKEN="$(openssl rand -hex 24)"
cat > apps/web/.env <<EOF
# Generated by SETUP-MAC.sh on $(date +%F). Local dev only — never commit.
NEXT_TELEMETRY_DISABLED=1
TURBO_TELEMETRY_DISABLED=1
DATABASE_URL=postgresql://biocatalyst:biocatalyst@127.0.0.1:5432/biocatalyst_dev
APP_BASE_URL=http://localhost:3000
ADMIN_TOKEN=${ADMIN_TOKEN}
ADMIN_EMAILS=bio1941999@gmail.com
EOF
echo "    config written"

echo "==> 6/7 Installing dependencies, migrating + seeding the database..."
export NEXT_TELEMETRY_DISABLED=1 TURBO_TELEMETRY_DISABLED=1
export DATABASE_URL="postgresql://biocatalyst:biocatalyst@127.0.0.1:5432/biocatalyst_dev"
pnpm install
pnpm --filter @biocatalyst/db --filter @biocatalyst/data build >/dev/null
pnpm --filter @biocatalyst/db migrate
pnpm --filter @biocatalyst/data seed:db

echo "==> 7/7 Building the web app (takes a few minutes)..."
pnpm --filter @biocatalyst/web build

echo ""
echo "=================================================================="
echo "  Done! Starting the app now — keep this Terminal window open."
echo ""
echo "  Open in your browser:  http://localhost:3000"
echo ""
echo "  Admin API token (only needed for /api/v1/admin/* calls):"
echo "    ${ADMIN_TOKEN}"
echo "  (also saved in apps/web/.env as ADMIN_TOKEN)"
echo ""
echo "  Stop the server anytime with Ctrl+C. Re-run ./SETUP-MAC.sh to"
echo "  start it again."
echo "=================================================================="
pnpm --filter @biocatalyst/web start
